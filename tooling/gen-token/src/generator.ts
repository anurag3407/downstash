/**
 * @file tooling/gen-token/src/generator.ts
 * Pure logic for `gen-token`: parse a `databases.toml`, hash tokens with
 * SHA-256, and render `supabase/seed.sql`. No I/O here — everything takes
 * and returns strings/objects so it is unit-testable.
 */
import { createHash } from 'node:crypto';

/** One token row as it will be inserted into `downstash.tokens`. */
export interface TokenRow {
  name: string;
  token_hash: string;
  db_slug: string;
  read_only: boolean;
  rate_per_sec: number | null;
  rate_burst: number | null;
  expires_at: string | null;
  metadata: string; // JSON string
}

/** One database row as it will be inserted into `downstash.databases`. */
export interface DatabaseRow {
  slug: string;
  name: string;
}

/**
 * Compute the SHA-256 hex digest of a token string. This matches what the
 * gateway stores so the raw token is never persisted.
 */
export function hashToken(token: string): string {
  return createHash('sha256').update(token, 'utf8').digest('hex');
}

/**
 * Very small TOML-subset parser. Supports the exact shape used by
 * `databases.toml`: string/int/bool values, single-line arrays of strings,
 * and `[[tokens]]` array-of-tables. Enough for the generator; not general TOML.
 */
export function parseDatabasesToml(src: string): DatabaseRow[] {
  const databases = new Map<string, DatabaseRow>();
  let currentTable: Record<string, TomlValue> | null = null;

  for (const rawLine of src.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (line === '' || line.startsWith('#')) continue;

    const tableMatch =
      /^\[\[([a-zA-Z0-9_.]+)\]\]$/.exec(line) ?? /^\[([a-zA-Z0-9_.]+)\]$/.exec(line);
    if (tableMatch) {
      const path = (tableMatch[1] ?? '').split('.');
      currentTable = {};
      if (path[0] === 'databases') {
        const slug = String(currentTable['slug'] ?? '');
        databases.set(slug, { slug, name: '' });
      }
      // For [[tokens]] we don't need a persistent object in this minimal parser.
      continue;
    }

    const kv = /^([a-zA-Z0-9_]+)\s*=\s*(.+)$/.exec(line);
    if (kv && currentTable) {
      currentTable[kv[1] ?? ''] = parseTomlValue((kv[2] ?? '').trim());
    }
  }
  return [...databases.values()];
}

type TomlValue = string | number | boolean | string[] | null;

function parseTomlValue(raw: string): TomlValue {
  if (raw === 'true') return true;
  if (raw === 'false') return false;
  if (raw.startsWith('[') && raw.endsWith(']')) {
    const inner = raw.slice(1, -1).trim();
    if (inner === '') return [];
    return inner.split(',').map((s) => parseTomlValue(s.trim()) as string);
  }
  if (raw.startsWith('"') && raw.endsWith('"')) return raw.slice(1, -1);
  if (raw.startsWith("'") && raw.endsWith("'")) return raw.slice(1, -1);
  if (/^-?\d+$/.test(raw)) return Number(raw);
  return raw;
}

/**
 * SQL-escape a string literal (single quotes doubled). Values are validated
 * beforehand so this is a defence-in-depth measure, not the only guard.
 */
export function sqlString(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

/** Quote a JSON string value for SQL jsonb literal. */
export function sqlJson(value: unknown): string {
  return `${sqlString(JSON.stringify(value))}::jsonb`;
}

/**
 * Render the full `supabase/seed.sql` content given databases and token rows.
 * Uses `on conflict do nothing` so the seed is idempotent.
 */
export function renderSeedSql(databases: DatabaseRow[], tokens: TokenRow[]): string {
  const lines: string[] = [];
  lines.push('-- Generated by pnpm gen:token. DO NOT EDIT BY HAND.');
  lines.push('-- Contains SHA-256 hashes only; raw tokens are never stored.');
  lines.push('');

  if (databases.length > 0) {
    lines.push('insert into downstash.databases (slug, name) values');
    const rows = databases.map((d) => `  (${sqlString(d.slug)}, ${sqlString(d.name)})`);
    lines.push(rows.join(',\n'));
    lines.push('on conflict (slug) do nothing;');
    lines.push('');
  }

  if (tokens.length > 0) {
    lines.push('insert into downstash.tokens');
    lines.push(
      '  (name, token_hash, db_slug, read_only, rate_per_sec, rate_burst, expires_at, metadata)'
    );
    lines.push('values');
    const rows = tokens.map((t) => {
      const ratePerSec = t.rate_per_sec === null ? 'null' : String(t.rate_per_sec);
      const rateBurst = t.rate_burst === null ? 'null' : String(t.rate_burst);
      const expiresAt = t.expires_at === null ? 'null' : sqlString(t.expires_at);
      return (
        `  (${sqlString(t.name)}, ${sqlString(t.token_hash)}, ${sqlString(t.db_slug)}, ` +
        `${t.read_only}, ${ratePerSec}, ${rateBurst}, ${expiresAt}, ${t.metadata})`
      );
    });
    lines.push(rows.join(',\n'));
    lines.push('on conflict (token_hash) do nothing;');
    lines.push('');
  }

  return lines.join('\n') + '\n';
}
